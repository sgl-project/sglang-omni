import SwiftUI

enum AppSVGIconKind: Hashable {
    case listView
    case linearView
    case viewDetails
    case historyDetails
    case copy
    case edit
    case delete
    case more
}

struct AppSVGIcon: View {
    let kind: AppSVGIconKind
    var color: Color = .secondary
    var size: CGFloat = 16

    var body: some View {
        ZStack {
            ForEach(definition.fillPaths, id: \.self) { pathData in
                SVGPathShape(pathData: pathData)
                    .fill(color)
            }

            ForEach(definition.strokePaths, id: \.self) { pathData in
                SVGPathShape(pathData: pathData)
                    .stroke(
                        color,
                        style: StrokeStyle(
                            lineWidth: definition.strokeWidth,
                            lineCap: .round,
                            lineJoin: .round
                        )
                    )
            }
        }
        .frame(width: size, height: size)
        .accessibilityHidden(true)
    }

    private var definition: AppSVGIconDefinition {
        AppSVGIconCatalog.definition(for: kind)
    }
}

struct AppSVGMenuLabel: View {
    let title: String
    let icon: AppSVGIconKind
    var color: Color = .primary
    var iconSize: CGFloat = 14

    var body: some View {
        Label {
            Text(title)
        } icon: {
            AppSVGIcon(kind: icon, color: color, size: iconSize)
        }
    }
}

struct AppSVGMenuButton<MenuContent: View>: View {
    let icon: AppSVGIconKind
    var color: Color = .secondary
    var size: CGFloat = 24
    var iconSize: CGFloat = 14
    let menuContent: MenuContent

    init(
        icon: AppSVGIconKind,
        color: Color = .secondary,
        size: CGFloat = 24,
        iconSize: CGFloat = 14,
        @ViewBuilder menuContent: () -> MenuContent
    ) {
        self.icon = icon
        self.color = color
        self.size = size
        self.iconSize = iconSize
        self.menuContent = menuContent()
    }

    var body: some View {
        Menu {
            menuContent
        } label: {
            Color.clear
                .frame(width: size, height: size)
                .contentShape(Rectangle())
        }
        .menuStyle(.borderlessButton)
        .menuIndicator(.hidden)
        .frame(width: size, height: size)
        .overlay {
            AppSVGIcon(kind: icon, color: color, size: iconSize)
                .allowsHitTesting(false)
        }
    }
}

