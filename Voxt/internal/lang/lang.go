// Package lang is the language table: every language a model in the
// catalogue may speak or understand, as embedded data. It covers
// OmniVoice's 646 languages and Whisper's 100 (99 + Cantonese), 652 in all,
// with English, native and Simplified Chinese names, the usual script, an
// RTL flag, the likely region and its flag.
//
// Codes are BCP-47 primary language subtags: ISO 639-1 when one exists,
// else ISO 639-3 (OmniVoice's convention). Lookup also accepts full tags
// ("zh-Hans-CN"), ISO 639-3 and 639-2/B codes ("cmn", "fre") and legacy
// codes ("iw", Whisper's "jw").
//
// Data: languages.tsv and aliases.tsv, generated by gen/main.go from the
// OmniVoice and Whisper lists and Unicode CLDR 48.2.
package lang

import (
	_ "embed"
	"slices"
	"strings"
	"sync"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

// Language is one row of the table.
type Language struct {
	Code        string // "zh", "en", "arb"
	ISO639_3    string // "cmn", "eng", "arb"
	Name        string // English name: "Chinese"
	Native      string // the name in the language itself ("中文"); "" when unknown
	Script      string // ISO 15924 code of the usual script: "Hans", "Latn", "Arab"
	RTL         bool   // the usual script is written right to left
	Region      string // likely region: ISO 3166-1 alpha-2, or a UN M49 number ("001")
	Macro       string // the macrolanguage it belongs to, if any ("arb" → "ar")
	OmniVoice   bool   // in OmniVoice's list
	Whisper     bool   // in Whisper's list
	WhisperCode string // Whisper's code when it differs from Code ("jw" for "jv")

	zh string
}

// Flag is the flag emoji of the likely region, or "" when the region is
// not a country (Esperanto's "001").
func (l Language) Flag() string {
	if len(l.Region) != 2 || l.Region[0] < 'A' || l.Region[0] > 'Z' || l.Region[1] < 'A' || l.Region[1] > 'Z' {
		return ""
	}
	return string([]rune{0x1F1E6 + rune(l.Region[0]-'A'), 0x1F1E6 + rune(l.Region[1]-'A')})
}

// NameIn is the language's name for a UI in locale: the Simplified Chinese
// name for "zh…" locales when known, else the English name.
func (l Language) NameIn(locale string) string {
	if strings.HasPrefix(strings.ToLower(locale), "zh") && l.zh != "" {
		return l.zh
	}
	return l.Name
}

//go:embed languages.tsv
var languagesTSV string

//go:embed aliases.tsv
var aliasesTSV string

type table struct {
	all     []Language // sorted by English name
	byCode  map[string]int
	aliases map[string]string
	folded  [][]string // per row: code, iso3, aliases, names (folded)
}

var load = sync.OnceValue(func() *table {
	t := &table{byCode: map[string]int{}, aliases: map[string]string{}}
	for _, line := range strings.Split(languagesTSV, "\n") {
		if line == "" || line[0] == '#' {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 11 {
			panic("lang: bad languages.tsv line: " + line)
		}
		t.all = append(t.all, Language{
			Code: f[0], ISO639_3: f[1], Name: f[2], Native: f[3], zh: f[4], Script: f[5], RTL: f[6] == "1",
			Region: f[7], Macro: f[8], OmniVoice: strings.Contains(f[9], "o"), Whisper: strings.Contains(f[9], "w"),
			WhisperCode: f[10],
		})
	}
	slices.SortStableFunc(t.all, func(a, b Language) int { return strings.Compare(Fold(a.Name), Fold(b.Name)) })
	for i, l := range t.all {
		t.byCode[l.Code] = i
	}
	for _, line := range strings.Split(aliasesTSV, "\n") {
		if line == "" || line[0] == '#' {
			continue
		}
		a, c, _ := strings.Cut(line, "\t")
		t.aliases[a] = c
	}
	for _, l := range t.all {
		if l.ISO639_3 != l.Code {
			t.aliases[l.ISO639_3] = l.Code
		}
		if l.WhisperCode != "" {
			t.aliases[l.WhisperCode] = l.Code
		}
	}
	extra := map[string][]string{}
	for a, c := range t.aliases {
		extra[c] = append(extra[c], a)
	}
	t.folded = make([][]string, len(t.all))
	for i, l := range t.all {
		keys := []string{l.Code, l.ISO639_3}
		keys = append(keys, extra[l.Code]...)
		t.folded[i] = append(keys, Fold(l.Name), Fold(l.Native), Fold(l.zh))
	}
	return t
})

// All returns every language, sorted by English name. The slice is a copy.
func All() []Language { return slices.Clone(load().all) }

// Len is the number of languages in the table.
func Len() int { return len(load().all) }

// Canonical returns the table code for a tag or alias ("zh-Hans-CN" → "zh",
// "cmn" → "zh", "iw" → "he", "jw" → "jv"), or "" when unknown.
func Canonical(tag string) string {
	t := load()
	tag = strings.ToLower(strings.TrimSpace(strings.ReplaceAll(tag, "_", "-")))
	if tag == "" {
		return ""
	}
	base, _, _ := strings.Cut(tag, "-")
	for _, c := range []string{tag, base} {
		if _, ok := t.byCode[c]; ok {
			return c
		}
		if a, ok := t.aliases[c]; ok {
			return a
		}
	}
	return ""
}

// Lookup finds a language by code, tag or alias (see Canonical).
func Lookup(tag string) (Language, bool) {
	c := Canonical(tag)
	if c == "" {
		return Language{}, false
	}
	t := load()
	return t.all[t.byCode[c]], true
}

// Fold is the search form of s: NFD, combining marks removed, lower-case,
// white space collapsed. "Français" and "francais" fold alike.
func Fold(s string) string {
	var b strings.Builder
	space := false
	for _, r := range norm.NFD.String(s) {
		switch {
		case unicode.Is(unicode.Mn, r):
			continue
		case unicode.IsSpace(r):
			space = b.Len() > 0
			continue
		}
		if space {
			b.WriteByte(' ')
			space = false
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return norm.NFC.String(b.String())
}

// Search returns the languages matching query by code, alias or any name
// (English, native, Chinese), case- and diacritic-insensitively, best
// first: exact code, exact name, name prefix, word prefix, substring. An
// empty query returns All().
func Search(query string) []Language {
	q := Fold(query)
	if q == "" {
		return All()
	}
	t := load()
	type hit struct {
		rank, i int
	}
	var hits []hit
	for i, keys := range t.folded {
		best := -1
		for k, key := range keys {
			if key == "" {
				continue
			}
			isCode := k < len(keys)-3
			r := -1
			switch {
			case key == q && isCode:
				r = 0
			case key == q:
				r = 1
			case isCode:
			case strings.HasPrefix(key, q):
				r = 2
			case strings.Contains(key, " "+q) || strings.Contains(key, "("+q) || strings.Contains(key, "-"+q):
				r = 3
			case strings.Contains(key, q):
				r = 4
			}
			if r >= 0 && (best < 0 || r < best) {
				best = r
			}
		}
		if best >= 0 {
			hits = append(hits, hit{best, i})
		}
	}
	slices.SortStableFunc(hits, func(a, b hit) int { return a.rank - b.rank })
	out := make([]Language, len(hits))
	for i, h := range hits {
		out[i] = t.all[h.i]
	}
	return out
}

// OmniVoiceCodes and WhisperCodes are the codes each model takes, in the
// model's own spelling (Whisper: "jw", "tl").
func OmniVoiceCodes() []string {
	var out []string
	for _, l := range load().all {
		if l.OmniVoice {
			out = append(out, l.Code)
		}
	}
	slices.Sort(out)
	return out
}

func WhisperCodes() []string {
	var out []string
	for _, l := range load().all {
		if l.Whisper {
			c := l.Code
			if l.WhisperCode != "" {
				c = l.WhisperCode
			}
			out = append(out, c)
		}
	}
	slices.Sort(out)
	return out
}

// Match reports whether a model whose language parameter accepts the
// codes in supported (any spelling Lookup understands, e.g. a catalogue's
// "en-US") can speak code, and which of its codes to pass. An exact
// language wins over a macrolanguage relation ("arb" matches a model that
// lists "ar", and the other way round).
func Match(supported []string, code string) (string, bool) {
	c := Canonical(code)
	if c == "" {
		return "", false
	}
	for _, s := range supported {
		if strings.EqualFold(strings.ReplaceAll(s, "_", "-"), strings.ReplaceAll(code, "_", "-")) {
			return s, true
		}
	}
	l, _ := Lookup(c)
	macroHit := ""
	for _, s := range supported {
		sc := Canonical(s)
		if sc == "" {
			continue
		}
		if sc == c {
			return s, true
		}
		if macroHit == "" {
			if sl, ok := Lookup(sc); ok && (l.Macro == sc || sl.Macro == c) {
				macroHit = s
			}
		}
	}
	return macroHit, macroHit != ""
}

// Option is a language in a picker for one model.
type Option struct {
	Language
	Supported bool   // the model can speak it
	ModelCode string // what to pass to the model (see Match); "" when unsupported
}

// Annotate marks each of langs as supported or not by a model, for a
// picker that shows unsupported languages disabled.
func Annotate(langs []Language, supported []string) []Option {
	out := make([]Option, len(langs))
	for i, l := range langs {
		mc, ok := Match(supported, l.Code)
		out[i] = Option{Language: l, Supported: ok, ModelCode: mc}
	}
	return out
}

// ForModel lists the languages a model supports, one per supported code,
// in the table's order. Codes the table does not know are skipped.
func ForModel(supported []string) []Option {
	t := load()
	want := map[string]string{}
	for _, s := range supported {
		if c := Canonical(s); c != "" {
			if _, dup := want[c]; !dup {
				want[c] = s
			}
		}
	}
	var out []Option
	for _, l := range t.all {
		if s, ok := want[l.Code]; ok {
			out = append(out, Option{Language: l, Supported: true, ModelCode: s})
		}
	}
	return out
}
